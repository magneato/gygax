#!/usr/bin/env bash
# Compile glyder's GLSL to SPIR-V and embed it in src/render/shaders.inc. Normal builds use the
# checked-in shaders.inc and need no shader compiler; run this after editing a shader.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
glslc="${GLSLC:-$(command -v glslc || ls "${ANDROID_HOME:-$HOME/Android/Sdk}"/ndk/*/shader-tools/linux-x86_64/glslc 2>/dev/null | sort -V | tail -1)}"
[ -x "$glslc" ] || { echo "glslc not found; set GLSLC or install the Android NDK or shaderc" >&2; exit 1; }
out="$here/../src/render/shaders.inc"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by glyder/shaders/compile.sh from glyder/shaders/*.vert|frag. Do not edit."
    for src in mesh.vert mesh.frag sky.vert sky.frag line.vert glow.frag solid.frag panel.vert panel.frag post.vert post.frag; do
        [ -f "$here/$src" ] || continue
        name="$(echo "$src" | tr '.' '_')"
        "$glslc" --target-env=vulkan1.1 -O -I "$here" "$here/$src" -o "$tmp/$name.spv"
        echo "inline constexpr std::uint32_t k_${name}[] = {"
        od -An -v -tx4 -w32 "$tmp/$name.spv" | sed -E 's/ ([0-9a-f]{8})/0x\1u,/g; s/^/   /'
        echo "};"
    done
} > "$out"
echo "wrote $out ($(grep -c '^inline' "$out") shaders, glslc $("$glslc" --version | head -1))"
